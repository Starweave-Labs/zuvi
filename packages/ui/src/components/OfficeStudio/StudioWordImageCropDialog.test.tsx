import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { StudioWordImageCropDialog } from './StudioWordImageCropDialog';
afterEach(cleanup);
it('previews crop edges, rejects hidden regions, resets and cancels without saving', () => {
  const save = vi.fn(), close = vi.fn();
  render(<StudioWordImageCropDialog src="data:image/png;base64,iVBORw0KGgo=" initial={{ left: 25 }} blocked={false} onSave={save} onClose={close} />);
  expect(screen.getByLabelText('保留的裁剪区域').style.inset).toBe('0% 0% 0% 25%');
  fireEvent.change(screen.getByRole('spinbutton', { name: '右边裁剪百分比' }), { target: { value: '80' } });
  expect(screen.getByRole('alert')).toHaveTextContent('可见图片');
  expect(screen.getByRole('button', { name: '应用裁剪' })).toBeDisabled();
  fireEvent.click(screen.getByRole('button', { name: '重置裁剪' }));
  expect(screen.getByRole('spinbutton', { name: '左边裁剪百分比' })).toHaveValue(0);
  fireEvent.click(screen.getByRole('button', { name: '取消' }));
  expect(close).toHaveBeenCalledOnce();
  expect(save).not.toHaveBeenCalled();
});
it('commits a crop only after composition ends and keeps blocked dialogs disabled', () => {
  const save = vi.fn();
  const { rerender } = render(<StudioWordImageCropDialog src="data:image/png;base64,iVBORw0KGgo=" initial={null} blocked={false} onSave={save} onClose={vi.fn()} />);
  const input = screen.getByRole('spinbutton', { name: '左边裁剪百分比' });
  fireEvent.change(input, { target: { value: '10' } });
  fireEvent.compositionStart(input);
  expect(screen.getByRole('button', { name: '应用裁剪' })).toBeDisabled();
  fireEvent.compositionEnd(input);
  fireEvent.click(screen.getByRole('button', { name: '应用裁剪' }));
  expect(save).toHaveBeenCalledWith({ left: 10, top: 0, right: 0, bottom: 0 });
  rerender(<StudioWordImageCropDialog src="data:image/png;base64,iVBORw0KGgo=" initial={null} blocked onSave={save} onClose={vi.fn()} />);
  expect(input).toBeDisabled();
  expect(screen.getByRole('button', { name: '重置裁剪' })).toBeDisabled();
  expect(screen.getByRole('button', { name: '应用裁剪' })).toBeDisabled();
});
it('previews pointer cropping and restores the draft on pointer cancellation', () => {
  const save = vi.fn();
  render(<StudioWordImageCropDialog src="data:image/png;base64,iVBORw0KGgo=" initial={{ left: 25 }} blocked={false} onSave={save} onClose={vi.fn()} />);
  const region = screen.getByLabelText('保留的裁剪区域');
  vi.spyOn(region.parentElement!, 'getBoundingClientRect').mockReturnValue({ width: 200, height: 100, x: 0, y: 0, left: 0, right: 200, top: 0, bottom: 100, toJSON() {} });
  const handle = screen.getByRole('button', { name: '拖动左边裁剪' });
  handle.setPointerCapture = vi.fn();
  const pointer = (type: string, clientX = 0) => { const event = new MouseEvent(type, { bubbles: true, clientX, clientY: 50 }); Object.defineProperty(event, 'pointerId', { value: 1 }); fireEvent(handle, event); };
  pointer('pointerdown', 50);
  pointer('pointermove', 70);
  expect(screen.getByRole('spinbutton', { name: '左边裁剪百分比' })).toHaveValue(35);
  pointer('pointercancel');
  expect(screen.getByRole('spinbutton', { name: '左边裁剪百分比' })).toHaveValue(25);
  expect(save).not.toHaveBeenCalled();
});
it('removes drag listeners when permissions change or the dialog unmounts', () => {
  const props = { src: 'data:image/png;base64,iVBORw0KGgo=', initial: { left: 25 }, onSave: vi.fn(), onClose: vi.fn() };
  const { rerender, unmount } = render(<StudioWordImageCropDialog {...props} blocked={false} />);
  const region = screen.getByLabelText('保留的裁剪区域');
  vi.spyOn(region.parentElement!, 'getBoundingClientRect').mockReturnValue({ width: 200, height: 100, x: 0, y: 0, left: 0, right: 200, top: 0, bottom: 100, toJSON() {} });
  const handle = screen.getByRole('button', { name: '拖动左边裁剪' });
  handle.setPointerCapture = vi.fn();
  const removed = vi.spyOn(handle, 'removeEventListener');
  const pointer = (type: string, clientX = 0) => { const event = new MouseEvent(type, { bubbles: true, clientX }); Object.defineProperty(event, 'pointerId', { value: 1 }); fireEvent(handle, event); };
  pointer('pointerdown', 50);
  rerender(<StudioWordImageCropDialog {...props} blocked />);
  pointer('pointermove', 100);
  expect(screen.getByRole('spinbutton', { name: '左边裁剪百分比' })).toHaveValue(25);
  expect(removed).toHaveBeenCalledWith('pointermove', expect.any(Function));
  rerender(<StudioWordImageCropDialog {...props} blocked={false} />);
  pointer('pointerdown', 50);
  removed.mockClear(); unmount();
  expect(removed).toHaveBeenCalledWith('pointermove', expect.any(Function));
  expect(props.onSave).not.toHaveBeenCalled();
});
