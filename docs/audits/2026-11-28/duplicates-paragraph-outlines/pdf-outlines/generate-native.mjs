import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const { pdfTestRuntime } = await import(path.join(root, 'docs/tests/studio-pdf-test-runtime.mjs'));
const require = createRequire(path.join(root, 'docs/package.json'));
const { PDFDocument, PDFName, PDFHexString, PDFArray, StandardFonts } = require('pdf-lib');
const codec = pdfTestRuntime().load('../src/pages/collaboration/office-studio/studio-pdf-outlines.ts');
const ids = ['alpha', 'beta', 'gamma'];
const output = process.argv[2] ? path.resolve(process.argv[2]) : path.join(path.dirname(fileURLToPath(import.meta.url)), 'native');
await mkdir(output, { recursive: true });
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const target = pageId => ({ pageId, view: { kind: 'Fit', parameters: [] } });
const node = (id, title, children, pageId) => ({ id, title, expanded: true, children, ...(pageId ? { target: target(pageId) } : {}) });
const key = name => PDFName.of(name);
const streamHashes = pdf => pdf.getPages().map(page => {
  const raw = page.node.Contents(), entries = raw instanceof PDFArray ? raw.asArray() : raw ? [raw] : [];
  return entries.map(ref => hash(pdf.context.lookup(ref).getContents()));
});
let pdf = await PDFDocument.create({ updateMetadata: false });
const font = await pdf.embedFont(StandardFonts.Helvetica);
for (let index = 0; index < ids.length; index++) pdf.addPage([300, 400]).drawText('Preserved page ' + index, { x: 30, y: 350, font });
const field = pdf.getForm().createTextField('Original field');
field.setText('original'); field.addToPage(pdf.getPages()[0], { x: 20, y: 30, width: 120, height: 22, font });
codec.writePdfOutlines(pdf, ids, [node('chapter', '章节', [node('child', 'Second page', [], ids[1])]), node('external', 'Passive vendor action', [])]);
const nativeRoot = pdf.catalog.lookup(key('Outlines')), passive = nativeRoot.lookup(key('Last'));
passive.set(key('A'), pdf.context.obj({ S: 'VendorAction', Payload: PDFHexString.fromText('preserve without executing') }));
passive.set(key('VendorData'), pdf.context.obj({ Mode: 'Preserve', Source: 7 }));
nativeRoot.set(key('VendorRoot'), PDFHexString.fromText('root-private'));
const originals = [];
const save = pdf => pdf.save({ useObjectStreams: false, updateFieldAppearances: false });
const source = await save(pdf);
await writeFile(path.join(output, 'source.pdf'), source);
const sourceHash = hash(source), streams = streamHashes(pdf), privateAction = passive.lookup(key('A')).toString();
pdf = await PDFDocument.load(source, { updateMetadata: false });
let tree = codec.readPdfOutlines(pdf, ids);
tree = codec.editPdfOutlineTree(tree, ids, { type: 'update', id: tree[0].id, title: '修改后的章节' });
tree = codec.editPdfOutlineTree(tree, ids, { type: 'insert', parentId: tree[0].id, index: 1, node: node('new-entry', 'Third page', [], ids[2]) });
for (let round = 1; round <= 2; round++) {
  codec.writePdfOutlines(pdf, ids, tree);
  const bytes = await save(pdf), filename = 'roundtrip-' + round + '.pdf';
  await writeFile(path.join(output, filename), bytes);
  pdf = await PDFDocument.load(bytes, { updateMetadata: false });
  tree = codec.readPdfOutlines(pdf, ids);
  assert.equal(tree[0].title, '修改后的章节'); assert.equal(tree[0].children.length, 2);
  assert.equal(tree[0].children[1].target.pageId, ids[2]);
  assert.deepEqual(streamHashes(pdf), streams);
  assert.equal(pdf.getForm().getTextField('Original field').getText(), 'original');
  const root = pdf.catalog.lookup(key('Outlines'));
  assert.equal(root.lookup(key('Last')).lookup(key('A')).toString(), privateAction);
  assert.equal(root.lookup(key('VendorRoot')).decodeText(), 'root-private');
  originals.push({ filename, bytes: bytes.length, sha256: hash(bytes), tree, streams });
}
assert.equal(hash(source), sourceHash);
assert.equal(hash(await readFile(path.join(output, 'source.pdf'))), sourceHash);
const summary = { milestone: 'P003 standalone kernel only', completeRequirement: false, source: { bytes: source.length, sha256: sourceHash }, nativeRounds: originals, fieldValue: 'original', sourceUnchanged: true, passiveActionRetained: true };
await writeFile(path.join(output, 'verification.json'), JSON.stringify(summary, null, 2) + String.fromCharCode(10));
process.stdout.write(JSON.stringify({ sourceUnchanged: true, nativeRounds: originals.length, completeRequirement: false }) + String.fromCharCode(10));
