#!/usr/bin/env python3
"""Preserve audit bytes around an explicitly cued whole-site browser run.

Only standard-library modules and read-only Git commands are used. Inventory is
advisory. Snapshot and restore require distinct explicit cue labels; neither is
run automatically. The current integration's validation, regeneration, and
preservation subtrees are excluded to avoid capturing changing closure logs or
the preservation process itself.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import sys
from datetime import datetime, timezone


INTEGRATION = PurePosixPath("2026-11-27/word-sheet-pdf-integration")
DEFAULT_EXCLUDES = tuple(
    str(INTEGRATION / name)
    for name in ("validation", "regenerated-history", "evidence-preservation")
)
TOPICS = (
    "word-basic-format", "sheet-view", "pdf-native-ui", "pdf-text-layer",
    "pdf-native-annotations", "static-entry-budget",
)
TEXT_ARCHIVE_SUFFIXES = {".log", ".txt", ".md"}
CHUNK = 1024 * 1024


def now() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256(path: Path) -> str:
    if path.is_symlink():
        return hashlib.sha256(os.fsencode(os.readlink(path))).hexdigest()
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(CHUNK), b""):
            digest.update(chunk)
    return digest.hexdigest()


def gzip_original(path: Path) -> dict:
    digest = hashlib.sha256()
    size = 0
    with gzip.open(path, "rb") as stream:
        for chunk in iter(lambda: stream.read(CHUNK), b""):
            digest.update(chunk)
            size += len(chunk)
    return {"bytes": size, "sha256": digest.hexdigest()}


def metadata(path: Path) -> dict:
    size = len(os.fsencode(os.readlink(path))) if path.is_symlink() else path.stat().st_size
    return {"bytes": size, "sha256": sha256(path)}


def path_kind(path: Path) -> str:
    return "symlink" if path.is_symlink() else "file"


def byte_identity(entry: dict) -> dict:
    return {key: entry[key] for key in ("bytes", "sha256")}


def source_identity(entry: dict) -> dict:
    return {"kind": entry["kind"], **byte_identity(entry)}


def evidence_class(relative: str) -> str:
    # These Fontconfig caches are generated by the saved render workflow. They
    # remain in the raw snapshot, but are not portable source/PDF/PNG evidence.
    return "runtime-font-cache" if "font-cache" in PurePosixPath(relative).parts else "audit-evidence"


def assert_metadata(path: Path, expected: dict) -> None:
    if not (path.is_file() or path.is_symlink()):
        raise ValueError(f"Missing or unsupported file: {path}")
    if expected.get("kind", path_kind(path)) != path_kind(path) or metadata(path) != byte_identity(expected):
        raise ValueError(f"Original bytes changed: {path}")


def safe_relative(value: str) -> PurePosixPath:
    relative = PurePosixPath(value)
    if not value or relative.is_absolute() or ".." in relative.parts:
        raise ValueError(f"Invalid relative path: {value!r}")
    if str(relative) != value or value == ".":
        raise ValueError(f"Non-canonical relative path: {value!r}")
    return relative


def repository(explicit: str | None) -> Path:
    if explicit:
        result = Path(explicit).resolve()
        if not (result / "docs/audits").is_dir():
            raise ValueError("--repo must contain docs/audits")
        return result
    for parent in Path(__file__).resolve().parents:
        if (parent / ".git").exists() and (parent / "docs/audits").is_dir():
            return parent
    raise ValueError("Cannot find repository; supply --repo")


def roots(repo: Path) -> tuple[Path, Path, Path]:
    audits = repo / "docs/audits"
    integration = audits.joinpath(*INTEGRATION.parts)
    return audits, integration, integration / "evidence-preservation"


def excluded(relative: str, prefixes: tuple[str, ...]) -> bool:
    return any(relative == prefix or relative.startswith(prefix + "/") for prefix in prefixes)


def audit_files(audits: Path, prefixes: tuple[str, ...]) -> dict[str, Path]:
    result = {}
    for directory, subdirs, names in os.walk(audits, followlinks=False):
        parent = Path(directory)
        kept = []
        for name in sorted(subdirs):
            path = parent / name
            relative = path.relative_to(audits).as_posix()
            if excluded(relative, prefixes):
                continue
            if path.is_symlink():
                result[relative] = path
                continue
            kept.append(name)
        subdirs[:] = kept
        for name in sorted(names):
            path = parent / name
            relative = path.relative_to(audits).as_posix()
            if excluded(relative, prefixes):
                continue
            if not (path.is_symlink() or path.is_file()):
                raise ValueError(f"Audit path is not a file or link: {path}")
            result[relative] = path
    return dict(sorted(result.items()))


def ignored_paths(repo: Path, paths: list[Path]) -> set[str]:
    if not paths:
        return set()
    relative = [path.relative_to(repo).as_posix() for path in paths]
    output = subprocess.run(
        ["git", "check-ignore", "-z", "--stdin"], cwd=repo,
        input=b"\0".join(os.fsencode(value) for value in relative) + b"\0",
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False,
    )
    if output.returncode not in (0, 1):
        raise ValueError(output.stderr.decode(errors="replace"))
    return {os.fsdecode(item) for item in output.stdout.split(b"\0") if item}


def write_json(path: Path, value: dict, *, replace: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w" if replace else "x", encoding="utf-8") as stream:
        json.dump(value, stream, ensure_ascii=False, indent=2)
        stream.write("\n")


def copy_verified(source: Path, destination: Path, expected: dict) -> None:
    assert_metadata(source, expected)
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists() or destination.is_symlink():
        raise ValueError(f"Refusing to overwrite preserved bytes: {destination}")
    if source.is_symlink():
        destination.symlink_to(os.readlink(source))
    else:
        shutil.copy2(source, destination)
    assert_metadata(source, expected)
    assert_metadata(destination, expected)


def archive_gzip(source: Path, destination: Path, expected: dict) -> dict:
    assert_metadata(source, expected)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("xb") as output:
        with gzip.GzipFile(filename="", fileobj=output, mode="wb", mtime=0) as stream:
            if source.is_symlink():
                stream.write(os.fsencode(os.readlink(source)))
            else:
                with source.open("rb") as input_stream:
                    shutil.copyfileobj(input_stream, stream, CHUNK)
    assert_metadata(source, expected)
    if gzip_original(destination) != {key: expected[key] for key in ("bytes", "sha256")}:
        raise ValueError(f"Gzip did not retain original bytes: {destination}")
    return metadata(destination)


def inventory(repo: Path, output: Path | None) -> dict:
    audits, _, _ = roots(repo)
    files = audit_files(audits, DEFAULT_EXCLUDES)
    ignored = ignored_paths(repo, list(files.values()))
    topics = []
    for topic in TOPICS:
        prefix = f"2026-11-27/{topic}/"
        entries = [{
            "path": path.relative_to(repo).as_posix(),
            "bytes": metadata(path)["bytes"] if path.is_symlink() else path.stat().st_size,
            "kind": path_kind(path),
            "evidenceClass": evidence_class(relative),
            **({"symlinkTarget": os.readlink(path)} if path.is_symlink() else {}),
            "ignoredByGit": path.relative_to(repo).as_posix() in ignored,
        } for relative, path in files.items() if relative.startswith(prefix)]
        topics.append({
            "topic": topic,
            "files": len(entries),
            "bytes": sum(entry["bytes"] for entry in entries),
            "ignored": [entry for entry in entries if entry["ignoredByGit"]],
            "runtimeCacheObjects": [entry for entry in entries if entry["evidenceClass"] == "runtime-font-cache"],
        })
    result = {
        "schemaVersion": 1,
        "status": "advisory-inventory-not-a-snapshot",
        "createdAt": now(),
        "excludes": list(DEFAULT_EXCLUDES),
        "topics": topics,
        "ignoredTopicFiles": sum(len(topic["ignored"]) for topic in topics),
        "ignoredTopicBytes": sum(entry["bytes"] for topic in topics for entry in topic["ignored"]),
    }
    if output:
        write_json(output, result, replace=True)
    return result


def snapshot(repo: Path, snapshot_dir: Path, cue: str, extra_excludes: list[str]) -> dict:
    audits, _, evidence = roots(repo)
    snapshot_dir = snapshot_dir.resolve()
    if snapshot_dir.is_relative_to(audits.resolve()):
        raise ValueError("Temporary snapshot must be outside docs/audits")
    for prefix in extra_excludes:
        safe_relative(prefix)
    prefixes = tuple(sorted(set(DEFAULT_EXCLUDES + tuple(extra_excludes))))
    if (evidence / "baseline-manifest.json").exists():
        raise ValueError("This integration already has a baseline; do not overwrite it")
    snapshot_dir.mkdir(parents=True, exist_ok=False)
    initial = audit_files(audits, prefixes)
    ignored = ignored_paths(repo, list(initial.values()))
    records = []
    for relative, source in initial.items():
        expected = {"kind": path_kind(source), **metadata(source)}
        copy_verified(source, snapshot_dir / "files" / relative, expected)
        records.append({
            "path": relative, **expected,
            "evidenceClass": evidence_class(relative),
            **({"symlinkTarget": os.readlink(source)} if source.is_symlink() else {}),
            "ignoredByGit": source.relative_to(repo).as_posix() in ignored,
        })
    final = audit_files(audits, prefixes)
    if set(initial) != set(final):
        raise ValueError("Audit file set changed during snapshot; wait for artifact writers")
    for record in records:
        assert_metadata(audits / record["path"], record)
    head = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=repo,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False,
    )
    baseline = {
        "schemaVersion": 1,
        "status": "complete-pre-e2e-audit-snapshot",
        "createdAt": now(), "cue": cue,
        "auditRoot": "docs/audits",
        "gitHead": head.stdout.decode().strip() if head.returncode == 0 else None,
        "excludes": list(prefixes),
        "fileCount": len(records),
        "symlinkCount": sum(entry["kind"] == "symlink" for entry in records),
        "runtimeCacheObjectCount": sum(entry["evidenceClass"] == "runtime-font-cache" for entry in records),
        "bytes": sum(record["bytes"] for record in records),
        "files": records,
    }
    write_json(snapshot_dir / "manifest.json", baseline)
    ignored_entries = []
    for record in records:
        if not record["ignoredByGit"]:
            continue
        archive = evidence / "ignored-originals" / (record["path"] + ".gz")
        compressed = archive_gzip(snapshot_dir / "files" / record["path"], archive, record)
        ignored_entries.append({
            "originalPath": "docs/audits/" + record["path"],
            "path": archive.relative_to(evidence).as_posix(),
            **compressed,
            "uncompressedOriginal": {key: record[key] for key in ("bytes", "sha256")},
            "originalKind": record["kind"],
        })
    write_json(evidence / "ignored-evidence-manifest.json", {
        "schemaVersion": 1,
        "reason": "Original ignored audit bytes are committed as gzip; existing specialty manifests and live originals are unchanged.",
        "baselineManifest": metadata(snapshot_dir / "manifest.json"),
        "fileCount": len(ignored_entries),
        "originalBytes": sum(entry["uncompressedOriginal"]["bytes"] for entry in ignored_entries),
        "files": ignored_entries,
    })
    # Publish the accepted baseline only after every ignored original has its
    # verified, non-ignored archive. A partial preservation run is not accepted.
    copy_verified(
        snapshot_dir / "manifest.json", evidence / "baseline-manifest.json",
        metadata(snapshot_dir / "manifest.json"),
    )
    return {"snapshot": str(snapshot_dir), "fileCount": len(records),
            "bytes": baseline["bytes"], "ignoredFilesArchived": len(ignored_entries)}


def load_baseline(repo: Path, snapshot_dir: Path | None) -> tuple[dict, Path]:
    _, _, evidence = roots(repo)
    path = evidence / "baseline-manifest.json"
    baseline = json.loads(path.read_text())
    if baseline.get("schemaVersion") != 1 or baseline.get("auditRoot") != "docs/audits":
        raise ValueError("Unsupported audit snapshot schema")
    if baseline.get("status") != "complete-pre-e2e-audit-snapshot":
        raise ValueError("Snapshot is incomplete")
    prefixes = tuple(baseline["excludes"])
    for prefix in prefixes:
        safe_relative(prefix)
    if not set(DEFAULT_EXCLUDES).issubset(prefixes):
        raise ValueError("Required exclusion prefixes are missing")
    seen = set()
    for entry in baseline["files"]:
        safe_relative(entry["path"])
        if entry["kind"] not in ("file", "symlink"):
            raise ValueError("Unsupported baseline object kind")
        if entry["kind"] == "symlink":
            target_bytes = os.fsencode(entry["symlinkTarget"])
            if len(target_bytes) != entry["bytes"] or hashlib.sha256(target_bytes).hexdigest() != entry["sha256"]:
                raise ValueError("Recorded symlink target differs from its original SHA")
        if entry["path"] in seen or excluded(entry["path"], prefixes):
            raise ValueError("Duplicate or excluded baseline path")
        seen.add(entry["path"])
    if (len(seen) != baseline["fileCount"]
            or sum(e["bytes"] for e in baseline["files"]) != baseline["bytes"]
            or sum(e["kind"] == "symlink" for e in baseline["files"]) != baseline["symlinkCount"]):
        raise ValueError("Baseline counts differ from file records")
    if snapshot_dir:
        assert_metadata(snapshot_dir / "manifest.json", metadata(path))
        for entry in baseline["files"]:
            assert_metadata(snapshot_dir / "files" / entry["path"], entry)
    return baseline, path


def verify_archive(repo: Path, evidence: Path, manifest: dict) -> None:
    for entry in manifest["files"]:
        relative = safe_relative(entry["path"])
        source = evidence.joinpath(*relative.parts)
        assert_metadata(source, entry)
        if "uncompressedOriginal" in entry:
            if gzip_original(source) != entry["uncompressedOriginal"]:
                raise ValueError(f"Archived original differs: {source}")


def verify(repo: Path, snapshot_dir: Path | None, allow_missing_ignored: bool) -> dict:
    audits, integration, evidence = roots(repo)
    baseline, baseline_path = load_baseline(repo, snapshot_dir)
    ignored_manifest = json.loads((evidence / "ignored-evidence-manifest.json").read_text())
    if ignored_manifest["baselineManifest"] != metadata(baseline_path):
        raise ValueError("Ignored archive points at a different baseline")
    verify_archive(repo, evidence, ignored_manifest)
    ignored = {entry["originalPath"].removeprefix("docs/audits/"): entry
               for entry in ignored_manifest["files"]}
    baseline_by_path = {entry["path"]: entry for entry in baseline["files"]}
    if set(ignored) != {entry["path"] for entry in baseline["files"] if entry["ignoredByGit"]}:
        raise ValueError("Ignored gzip archive coverage differs from baseline")
    if ignored_manifest["fileCount"] != len(ignored) or ignored_manifest["originalBytes"] != sum(e["uncompressedOriginal"]["bytes"] for e in ignored.values()):
        raise ValueError("Ignored gzip archive counts are inconsistent")
    for relative, entry in ignored.items():
        if entry["uncompressedOriginal"] != {key: baseline_by_path[relative][key]
                                               for key in ("bytes", "sha256")}:
            raise ValueError("Ignored gzip original differs from baseline")
        if entry["originalKind"] != baseline_by_path[relative]["kind"]:
            raise ValueError("Ignored original object kind differs from baseline")
    current = audit_files(audits, tuple(baseline["excludes"]))
    missing_allowed = set(ignored) if allow_missing_ignored else set()
    expected = {entry["path"] for entry in baseline["files"]}
    if set(current) - expected or expected - set(current) - missing_allowed:
        raise ValueError("Restored audit file set differs from baseline")
    missing = []
    for entry in baseline["files"]:
        source = audits / entry["path"]
        if source.is_file() or source.is_symlink():
            assert_metadata(source, entry)
        elif entry["path"] in missing_allowed:
            missing.append(entry["path"])
        else:
            raise ValueError(f"Missing baseline file: {source}")
    restored_path = evidence / "restoration-manifest.json"
    if restored_path.exists():
        restoration = json.loads(restored_path.read_text())
        if restoration["baselineManifest"] != metadata(baseline_path):
            raise ValueError("Restoration points at a different baseline")
        archive_paths = set()
        original_paths = set()
        changed = added = 0
        for entry in restoration["regenerated"]:
            archive_relative = safe_relative(entry["archivePath"])
            if not str(archive_relative).startswith("regenerated-history/"):
                raise ValueError("Regenerated archive is outside its dedicated subtree")
            original = entry["originalPath"].removeprefix("docs/audits/")
            safe_relative(original)
            if str(archive_relative) in archive_paths or original in original_paths:
                raise ValueError("Duplicate regenerated archive or original path")
            archive_paths.add(str(archive_relative))
            original_paths.add(original)
            if entry["change"] == "changed" and original in baseline_by_path:
                changed += 1
                expected_before = source_identity(baseline_by_path[original])
                if entry["before"] != expected_before:
                    raise ValueError("Regenerated before hash differs from baseline")
            elif entry["change"] == "added" and original not in baseline_by_path and entry["before"] is None:
                added += 1
            else:
                raise ValueError("Regenerated change identity is invalid")
            source = integration / str(archive_relative)
            assert_metadata(source, entry["archive"])
            if entry["encoding"] == "gzip":
                if gzip_original(source) != byte_identity(entry["after"]):
                    raise ValueError(f"Regenerated gzip differs: {source}")
            elif (entry["encoding"] != "original-bytes" or path_kind(source) != entry["after"]["kind"]
                  or metadata(source) != byte_identity(entry["after"])):
                raise ValueError(f"Regenerated original differs: {source}")
        actual_archives = {path.relative_to(integration).as_posix()
                           for path in (integration / "regenerated-history").rglob("*")
                           if path.is_file()}
        if archive_paths != actual_archives:
            raise ValueError("Regenerated directory and index differ")
        restored_missing = set()
        for entry in restoration["missingFilesRestored"]:
            relative = entry["originalPath"].removeprefix("docs/audits/")
            if relative in restored_missing or relative in original_paths or relative not in baseline_by_path:
                raise ValueError("Missing-file restoration identity is invalid")
            restored_missing.add(relative)
            if entry["before"] != source_identity(baseline_by_path[relative]):
                raise ValueError("Missing-file before hash differs from baseline")
        if (restoration["changedFiles"] != changed or restoration["addedFiles"] != added
                or restoration["restoredBaselineFiles"] != len(expected)
                or restoration["restoredBaselineBytes"] != baseline["bytes"]
                or restoration["unchangedFiles"] + changed + len(restored_missing) != len(expected)):
            raise ValueError("Restoration counts differ from complete file records")
    return {"verifiedBaselineFiles": len(expected), "baselineBytes": baseline["bytes"],
            "ignoredGzipFiles": len(ignored), "missingLiveIgnoredFilesVerifiedFromArchive": missing}


def restore(repo: Path, snapshot_dir: Path, cue: str) -> dict:
    audits, integration, evidence = roots(repo)
    baseline, baseline_path = load_baseline(repo, snapshot_dir)
    restoration_path = evidence / "restoration-manifest.json"
    regeneration = integration / "regenerated-history"
    if restoration_path.exists() or regeneration.exists():
        raise ValueError("This integration already has regenerated evidence; do not overwrite it")
    prefixes = tuple(baseline["excludes"])
    before = {entry["path"]: entry for entry in baseline["files"]}
    sources = audit_files(audits, prefixes)
    after = {relative: {"kind": path_kind(source), **metadata(source)} for relative, source in sources.items()}
    ignored = ignored_paths(repo, list(sources.values()))
    changed = sorted(relative for relative in after if relative not in before
                     or after[relative] != source_identity(before[relative]))
    missing = sorted(set(before) - set(after))
    regeneration.mkdir(parents=True, exist_ok=False)
    retained = []
    for relative in changed:
        source = sources[relative]
        compress = (source.is_symlink() or source.suffix.lower() in TEXT_ARCHIVE_SUFFIXES
                    or source.relative_to(repo).as_posix() in ignored)
        if compress:
            archive = regeneration / "gzip" / (relative + ".gz")
            archived = archive_gzip(source, archive, after[relative])
        else:
            archive = regeneration / "files" / relative
            copy_verified(source, archive, after[relative])
            archived = metadata(archive)
        retained.append({
            "originalPath": "docs/audits/" + relative,
            "change": "changed" if relative in before else "added",
            "before": source_identity(before[relative]) if relative in before else None,
            "after": after[relative],
            "archivePath": archive.relative_to(integration).as_posix(),
            "encoding": "gzip" if compress else "original-bytes",
            "archive": archived,
        })
    pre_restore = audit_files(audits, prefixes)
    if set(pre_restore) != set(sources):
        raise ValueError("Audit file set changed while archiving; no originals were restored")
    for relative, source in pre_restore.items():
        assert_metadata(source, after[relative])
    # All original snapshots and generated copies have been verified before any
    # live audit is overwritten or a newly generated file is removed.
    for relative in changed:
        if relative not in before:
            sources[relative].unlink()
    for relative in sorted(set(changed) | set(missing)):
        if relative not in before:
            continue
        source = snapshot_dir / "files" / relative
        destination = audits / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.is_file() or destination.is_symlink():
            destination.unlink()
        elif destination.is_dir():
            # A previous directory link may have become a real directory. All
            # contained new files have already been retained and removed above.
            # Remove only empty directories; never follow links or erase files.
            for directory, subdirs, files in os.walk(destination, topdown=False, followlinks=False):
                if files or any((Path(directory) / name).is_symlink() for name in subdirs):
                    raise ValueError(f"Unarchived contents prevent restoration: {destination}")
                Path(directory).rmdir()
        copy_verified(source, destination, before[relative])
    restoration = {
        "schemaVersion": 1,
        "status": "restored-baseline-with-regenerated-bytes-retained",
        "createdAt": now(), "cue": cue,
        "baselineManifest": metadata(baseline_path),
        "restoredBaselineFiles": len(before),
        "restoredBaselineBytes": baseline["bytes"],
        "unchangedFiles": len(before) - len([r for r in retained if r["change"] == "changed"]) - len(missing),
        "changedFiles": len([r for r in retained if r["change"] == "changed"]),
        "addedFiles": len([r for r in retained if r["change"] == "added"]),
        "missingFilesRestored": [{"originalPath": "docs/audits/" + relative,
                                  "before": source_identity(before[relative])}
                                 for relative in missing],
        "regenerated": retained,
    }
    write_json(restoration_path, restoration)
    result = verify(repo, snapshot_dir, False)
    return {**result, "changedFiles": restoration["changedFiles"],
            "addedFiles": restoration["addedFiles"], "missingFilesRestored": len(missing),
            "regeneratedDirectory": str(regeneration)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", help="Repository root; otherwise derive it from this saved script")
    commands = parser.add_subparsers(dest="command", required=True)
    inventory_parser = commands.add_parser("inventory", help="Advisory names/bytes only; does not freeze artifacts")
    inventory_parser.add_argument("--output", type=Path)
    snapshot_parser = commands.add_parser("snapshot", help="Only after the parent explicitly cues pre-E2E preservation")
    snapshot_parser.add_argument("--snapshot-dir", required=True, type=Path)
    snapshot_parser.add_argument("--cue", required=True)
    snapshot_parser.add_argument("--exclude-prefix", action="append", default=[])
    restore_parser = commands.add_parser("restore", help="Only after the parent explicitly cues post-E2E restoration")
    restore_parser.add_argument("--snapshot-dir", required=True, type=Path)
    restore_parser.add_argument("--cue", required=True)
    verify_parser = commands.add_parser("verify", help="Read-only byte and gzip checks; optionally check temporary backups")
    verify_parser.add_argument("--snapshot-dir", type=Path)
    verify_parser.add_argument("--allow-missing-ignored", action="store_true")
    args = parser.parse_args()
    repo = repository(args.repo)
    if args.command == "inventory":
        result = inventory(repo, args.output)
    elif args.command == "snapshot":
        if not args.cue.strip():
            parser.error("--cue must name the explicit pre-E2E cue")
        result = snapshot(repo, args.snapshot_dir, args.cue, args.exclude_prefix)
    elif args.command == "restore":
        if not args.cue.strip():
            parser.error("--cue must name the explicit post-E2E cue")
        result = restore(repo, args.snapshot_dir, args.cue)
    else:
        result = verify(repo, args.snapshot_dir, args.allow_missing_ignored)
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as error:
        print(f"Audit preservation stopped: {error}", file=sys.stderr)
        raise SystemExit(1) from error
