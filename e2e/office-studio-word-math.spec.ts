import { expect, test } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import JSZip from '../docs/node_modules/jszip/lib/index.js';

test('edits native display equations and preserves scripts, fractions, matrices and formatting through repeated DOCX saves', async ({ page }) => {
  const audit = path.resolve('docs/audits/2026-11-26/word-math');
  const zip = await JSZip.loadAsync(await readFile('docs/audits/2026-11-26/word-image-crop/crop-source.docx'));
  const original = await zip.file('word/document.xml')!.async('string');
  const equation = '<w:p><m:oMathPara xmlns:m="http://schemas.openxmlformats.org/officeDocument/2006/math"><m:oMathParaPr><m:jc m:val="right"/></m:oMathParaPr><m:oMath><m:f><m:num><m:sSubSup><m:e><m:r><m:rPr><m:sty m:val="bi"/></m:rPr><m:t>x</m:t></m:r></m:e><m:sub><m:r><m:t>i</m:t></m:r></m:sub><m:sup><m:r><m:t>2</m:t></m:r></m:sup></m:sSubSup></m:num><m:den><m:r><m:t>2</m:t></m:r></m:den></m:f></m:oMath></m:oMathPara></w:p>';
  expect(original).toMatch(/<w:body>/);
  zip.file('word/document.xml', original.replace(/<w:body>[\s\S]*<\/w:body>/, `<w:body>${equation}<w:sectPr><w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1134" w:bottom="1134" w:left="1134" w:right="1134"/></w:sectPr></w:body>`));
  const source = await zip.generateAsync({ type: 'nodebuffer' });
  await writeFile(path.join(audit, 'math-source.docx'), source);
  await page.goto('/#/components/office-studio');
  const importFile = (buffer: Buffer, name: string) => page.getByLabel('导入文档文件', { exact: true }).setInputFiles({ name, mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer });
  await importFile(source, '原生数学公式.docx');
  const body = page.getByRole('textbox', { name: 'Word 文档正文', exact: true });
  const math = body.locator('span[data-word-math]');
  await expect(math.locator('mfrac')).toHaveCount(1);
  await expect(math.locator('msubsup')).toHaveCount(1);
  await math.click();
  await page.getByRole('tab', { name: '插入', exact: true }).click();
  await page.getByRole('button', { name: '数学公式', exact: true }).click();
  const before = await math.getAttribute('data-word-math');
  await page.getByRole('textbox', { name: '公式 段落内容 分子 基数文字', exact: true }).fill('cancelled');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await expect(math).toHaveAttribute('data-word-math', before!);
  await page.getByRole('button', { name: '数学公式', exact: true }).click();
  await page.getByRole('textbox', { name: '公式 段落内容 分子 基数文字', exact: true }).fill('a+1');
  const composing = page.getByRole('textbox', { name: '公式 段落内容 分子 基数文字', exact: true });
  await composing.dispatchEvent('compositionstart', { data: '甲' });
  await composing.fill('变量甲');
  await expect(page.getByRole('button', { name: '保存数学公式', exact: true })).toBeDisabled();
  await expect(math).toHaveAttribute('data-word-math', before!);
  await composing.dispatchEvent('compositionend', { data: '甲' });
  await composing.fill('a+1');
  await expect(page.getByRole('button', { name: '保存数学公式', exact: true })).toBeEnabled();

  await page.getByRole('textbox', { name: '公式 段落内容 分子 基数字号', exact: true }).fill('14.5pt');
  await page.getByRole('textbox', { name: '公式 段落内容 分子 基数文字颜色', exact: true }).fill('#aa2244');
  await page.getByRole('button', { name: '公式 段落内容 分母改为矩阵', exact: true }).click();
  await page.getByRole('textbox', { name: '公式 段落内容 分母 第1行第2列文字', exact: true }).fill('5');
  await page.getByRole('button', { name: '段落公式对齐center', exact: true }).click();
  await page.screenshot({ path: path.join(audit, 'math-dialog-light.png'), fullPage: true });
  await page.getByRole('button', { name: '保存数学公式', exact: true }).click();
  await expect(math.locator('mtable mtd')).toHaveCount(4);
  await expect(math.locator('msubsup mtext').first()).toHaveText('a+1');
  const edited = await math.getAttribute('data-word-math');
  await page.getByRole('tab', { name: '开始', exact: true }).click();
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(math).toHaveAttribute('data-word-math', before!);
  await page.getByRole('button', { name: '重做', exact: true }).click();
  await expect(math).toHaveAttribute('data-word-math', edited!);
  for (let round = 1; round <= 2; round++) {
    const pending = page.waitForEvent('download');
    await page.getByRole('button', { name: '导出文件', exact: true }).click();
    const bytes = await readFile((await (await pending).path())!);
    await writeFile(path.join(audit, `math-round-${round}.docx`), bytes);
    const saved = await JSZip.loadAsync(bytes);
    const native = await saved.file('word/document.xml')!.async('string');
    expect(native).toContain('<m:oMathPara'); expect(native).toContain('<m:sSubSup'); expect(native).toContain('<m:m>');
    expect(native).toContain('<m:sty m:val="bi"'); expect(native).toContain('<w:sz w:val="29"');
    await importFile(bytes, `数学重开${round}.docx`);
    await expect(math).toHaveAttribute('data-word-math', edited!);
  }
  await page.screenshot({ path: path.join(audit, 'math-light.png'), fullPage: true });
  await page.getByRole('button', { name: '切换暗色', exact: true }).click();
  await page.screenshot({ path: path.join(audit, 'math-dark.png'), fullPage: true });
  await math.click();
  await page.getByRole('tab', { name: '插入', exact: true }).click();
  await page.getByRole('button', { name: '数学公式', exact: true }).click();
  await page.screenshot({ path: path.join(audit, 'math-dialog-dark.png'), fullPage: true });
  await page.setViewportSize({ width: 320, height: 720 });
  await expect(page.getByRole('textbox', { name: '公式 段落内容 分子 基数文字', exact: true })).toBeVisible();
  await page.screenshot({ path: path.join(audit, 'math-dialog-320-overview.png'), fullPage: true });
  const size = page.getByRole('textbox', { name: '公式 段落内容 分子 基数字号', exact: true });
  await size.scrollIntoViewIfNeeded();
  await size.fill('0.1pt');
  await expect(page.getByRole('button', { name: '保存数学公式', exact: true })).toBeDisabled();
  await size.fill('14.5pt');
  await expect(page.getByRole('button', { name: '保存数学公式', exact: true })).toBeEnabled();
  const bounds = await size.boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0); expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(320);
  await page.screenshot({ path: path.join(audit, 'math-dialog-320.png'), fullPage: true });
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.screenshot({ path: path.join(audit, 'math-320.png'), fullPage: true });
  await page.getByRole('switch', { name: '只读预览', exact: true }).click();
  await expect(page.getByRole('button', { name: '数学公式', exact: true })).toBeDisabled();
  await expect(math).toHaveAttribute('data-word-math', edited!);
});
