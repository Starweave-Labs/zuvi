import { expect, test } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import JSZip from '../docs/node_modules/jszip/lib/index.js';

test('edits native bookmarks, cancels invalid drafts, undoes deletion and reopens internal links twice', async ({ page }) => {
  const audit = path.resolve('docs/audits/2026-11-26/word-bookmarks');
  await mkdir(audit, { recursive: true });
  const zip = await JSZip.loadAsync(await readFile('docs/audits/2026-11-26/word-math-groups/math-source.docx'));
  const xml = await zip.file('word/document.xml')!.async('string');
  zip.file('word/document.xml', xml.replace(/<w:body>[\s\S]*?(<w:sectPr[\s\S]*?<\/w:sectPr>)<\/w:body>/, '<w:body><w:p><w:bookmarkStart w:id="42" w:name="Here"/><w:r><w:t>Target</w:t></w:r><w:bookmarkEnd w:id="42"/></w:p><w:p><w:hyperlink w:anchor="Here"><w:r><w:rPr><w:b/></w:rPr><w:t>Go here</w:t></w:r></w:hyperlink></w:p>$1</w:body>'));
  const source = await zip.generateAsync({ type: 'nodebuffer' });
  await writeFile(path.join(audit, 'bookmarks-source.docx'), source);
  await page.goto('/#/components/office-studio');
  const importFile = (buffer: Buffer, name: string) => page.getByLabel('导入文档文件', { exact: true }).setInputFiles({ name, mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer });
  await importFile(source, 'Bookmarks.docx');
  const body = page.getByRole('textbox', { name: 'Word 文档正文', exact: true });
  await expect(body.locator('a')).toHaveAttribute('href', '#Here');
  await page.getByRole('tab', { name: '引用', exact: true }).click();
  await page.getByRole('button', { name: '书签', exact: true }).click();
  await page.getByRole('textbox', { name: '书签名称', exact: true }).fill('Here');
  await page.getByRole('button', { name: '添加书签', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('同名');
  await page.getByRole('button', { name: '删除书签 Here', exact: true }).click();
  await expect(body.locator('[data-word-bookmark]')).toHaveCount(0);
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('tab', { name: '开始', exact: true }).click();
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(body.locator('[data-word-bookmark]')).toHaveCount(2);
  await body.locator('a').click();
  await page.getByRole('tab', { name: '引用', exact: true }).click();
  await page.getByRole('button', { name: '链接', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '链接显示文字', exact: true })).toHaveValue('Go here');
  await page.getByRole('textbox', { name: '链接显示文字', exact: true }).fill('Jump 🧮');
  await page.screenshot({ path: path.join(audit, 'link-dialog-light.png'), fullPage: true });
  await page.getByRole('button', { name: '应用链接', exact: true }).click();
  await expect(body.locator('a')).toHaveText('Jump 🧮');
  await expect(body.locator('a strong, strong a')).toHaveText('Jump 🧮');
  await page.getByRole('tab', { name: '开始', exact: true }).click();
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(body.locator('a')).toHaveText('Go here');
  await page.getByRole('button', { name: '重做', exact: true }).click();
  await expect(body.locator('a')).toHaveText('Jump 🧮');
  for (let round = 1; round <= 2; round++) {
    const pending = page.waitForEvent('download');
    await page.getByRole('button', { name: '导出文件', exact: true }).click();
    const bytes = await readFile((await (await pending).path())!);
    await writeFile(path.join(audit, `bookmarks-round-${round}.docx`), bytes);
    await importFile(bytes, `Bookmarks-round-${round}.docx`);
    await expect(body.locator('[data-word-bookmark]')).toHaveCount(2);
    await expect(body.locator('a')).toHaveAttribute('href', '#Here');
    await expect(body.locator('a')).toHaveText('Jump 🧮');
  }
  await page.screenshot({ path: path.join(audit, 'bookmarks-light.png'), fullPage: true });
  await page.getByRole('button', { name: '切换暗色', exact: true }).click();
  await page.screenshot({ path: path.join(audit, 'bookmarks-dark.png'), fullPage: true });
  await body.locator('a').click();
  await page.getByRole('tab', { name: '引用', exact: true }).click();
  await page.getByRole('button', { name: '链接', exact: true }).click();
  await page.screenshot({ path: path.join(audit, 'link-dialog-dark.png'), fullPage: true });
  await page.setViewportSize({ width: 320, height: 720 });
  const label = page.getByRole('textbox', { name: '链接显示文字', exact: true });
  await label.scrollIntoViewIfNeeded();
  const bounds = await label.boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(320);
  await page.screenshot({ path: path.join(audit, 'link-dialog-320.png'), fullPage: true });
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('switch', { name: '只读预览', exact: true }).click();
  await expect(page.getByRole('button', { name: '链接', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '书签', exact: true }).click();
  await expect(page.getByRole('button', { name: '删除书签 Here', exact: true })).toBeDisabled();
  await page.screenshot({ path: path.join(audit, 'bookmark-dialog-320.png'), fullPage: true });
  await page.getByRole('button', { name: '跳转书签 Here', exact: true }).click();
  await expect(body).toHaveAttribute('contenteditable', 'false');
  await expect(body.locator('a')).toHaveText('Jump 🧮');
  await page.screenshot({ path: path.join(audit, 'bookmarks-320.png'), fullPage: true });
});
